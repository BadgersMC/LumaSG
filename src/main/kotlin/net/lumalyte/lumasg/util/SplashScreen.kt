    /**
     * Print the startup splash. [SECRET_CHANCE]% of the time, a random
     * secret splash is shown instead of the main banner.
     */
    fun print(plugin: JavaPlugin) {
        val version = plugin.pluginMeta.version
        val javaVersion = Runtime.version().toString()

        val roll = (Math.random() * 100).toInt()
        if (roll < SECRET_CHANCE && secretSplashes.isNotEmpty()) {
            val splash = secretSplashes.random()
                .replace("{version}", version)
                .replace("{java}", javaVersion)
            plugin.server.consoleSender.sendMessage("\n$splash\n")
        } else {
            printMainBanner(plugin, version, javaVersion)
        }
    }

